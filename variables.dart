void main() {
  var name = 'Hossein';
  name = 'Ali';

  final age = 18;

  const pi = 3.14;

  print('Name: $name');
  print('Age: $age');
  print('Pi: $pi');
}

// var: مقدار متغیر قابل تغییر است.

// final: مقدار متغیر فقط یک بار تعیین می‌شود.

// const: مقدار متغیر ثابت است و از ابتدا مشخص می‌شود.